// ARCH-MIG-01 slice 4b deliverable 6 — the first extraction benchmark run.
//
// MANUAL. Never in CI (it makes real model calls). Run once, by hand, against a
// running worker with real credentials, and commit the result.
//
//   # 1. seed a local worker (see the slice-4b brief / the slice-3 round-trip notes):
//   #    schema.sql + 0008 + 0009, publish national-redflags + ct_cap to KV/D1,
//   #    .dev.vars with ANTHROPIC_API_KEY + ASSESS_INTERNAL_KEY + ASSESS_PIPELINE_ENABLED=true
//   # 2. npx wrangler dev --config public/crr-criteria/wrangler.json --port 8787 --persist-to ./.wrangler/state
//   # 3. from repo root:
//   ASSESS_URL=http://localhost:8787 ASSESS_INTERNAL_KEY=<key> \
//     node tooling/criteria-bundle/benchmark/run-extraction-benchmark.mjs
//
// Writes benchmark/results/<date>-<provider>-<modelId>.md — per-indicator hits
// and misses, quote validity, exam/site selection, and the engine result for
// each of the four ground-truth cases. A miss is a FINDING, not a failure of the
// slice — report it honestly.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const gtDir = path.join(here, "ground-truth");
const resultsDir = path.join(here, "results");

const BASE = process.env.ASSESS_URL || "http://localhost:8787";
const KEY = process.env.ASSESS_INTERNAL_KEY;
if (!KEY) {
  console.error("Set ASSESS_INTERNAL_KEY (the x-assess-internal shared secret the worker expects).");
  process.exit(1);
}

const normalise = (s) => String(s ?? "").replace(/\s+/g, " ").trim().toLowerCase();

function collectAnswers(qr) {
  const out = new Map();
  const walk = (items) => {
    for (const i of items || []) {
      if (Array.isArray(i.item)) walk(i.item);
      if (!Array.isArray(i.answer)) continue;
      const a = i.answer[0] || {};
      const vk = Object.keys(a).find((k) => k.startsWith("value"));
      let value = vk ? a[vk] : undefined;
      if (value && typeof value === "object" && "code" in value) value = value.code;
      const ev = (a.extension || []).find((e) => e.url.endsWith("answer-evidence"));
      const sub = {};
      for (const s of ev?.extension || []) {
        if (s.url === "status") sub.status = s.valueCode;
        if (s.url === "quote") sub.quote = s.valueString;
      }
      out.set(i.linkId, { value, status: sub.status, quote: sub.quote });
    }
  };
  walk(qr.item);
  return out;
}

async function post(pathname, body) {
  const res = await fetch(BASE + pathname, {
    method: "POST",
    headers: { "content-type": "application/json", "x-assess-internal": KEY },
    body: JSON.stringify(body),
  });
  const json = await res.json().catch(() => ({}));
  return { status: res.status, json };
}

const files = fs.readdirSync(gtDir).filter((f) => f.endsWith(".json") && f !== "manifest.json").sort();
const cases = [];
let provider = "?";
let modelId = "?";

for (const file of files) {
  const gt = JSON.parse(fs.readFileSync(path.join(gtDir, file), "utf8"));
  const ex = await post("/api/assess/extract", {
    note: gt.note,
    requestedExamSite: gt.examSites?.[0]?.id,
    context: {},
  });
  if (ex.json.provider) provider = ex.json.provider;
  if (ex.json.modelId) modelId = ex.json.modelId;

  const rec = { id: gt.id, extractStatus: ex.status, validation: ex.json.validation, indicator: [], absent: [], examSel: null, engine: null };

  if (ex.status === 200 && ex.json.questionnaireResponse) {
    const got = collectAnswers(ex.json.questionnaireResponse);
    for (const [linkId, expected] of Object.entries(gt.expected)) {
      const g = got.get(linkId);
      rec.indicator.push({
        linkId,
        expected,
        got: g ?? null,
        valueMatch: g != null && String(g.value) === String(expected.value),
        statusMatch: g != null && g.status === expected.status,
        quoteValid: g != null && typeof g.quote === "string" && normalise(gt.note).includes(normalise(g.quote)),
      });
    }
    for (const linkId of Object.keys(gt.expectedAbsent || {})) {
      rec.absent.push({ linkId, falsePositive: got.has(linkId) });
    }
    rec.examSel = { expected: gt.examSites, got: ex.json.examSiteSelection };

    const ev = await post("/api/assess/evaluate", {
      questionnaireResponse: ex.json.questionnaireResponse,
      requestedExamSite: gt.examSites?.[0]?.id,
    });
    rec.engine = {
      status: ev.status,
      determination: ev.json?.requestedExam?.advisory?.determination ?? ev.json?.determination ?? null,
      expected: gt.engineExpectation?.determination ?? null,
    };
  }
  cases.push(rec);
}

// ── report ──
const date = new Date().toISOString().slice(0, 10);
let md = `# Extraction benchmark — ${date} — ${provider} / ${modelId}\n\n`;
md += `Generated by \`tooling/criteria-bundle/benchmark/run-extraction-benchmark.mjs\` against \`${BASE}\`. `;
md += `Four ground-truth cases; each note run through \`/api/assess/extract\` then the resulting QuestionnaireResponse through \`/api/assess/evaluate\`. A miss is a finding.\n\n`;

for (const c of cases) {
  md += `## ${c.id}\n\n`;
  md += `- extract: HTTP ${c.extractStatus}; gate ${c.validation?.passed === true ? "PASS" : "FAIL"}`;
  if (c.validation && !c.validation.passed) md += ` — ${(c.validation.failures || []).join("; ")}`;
  md += `\n`;
  if (c.indicator.length) {
    md += `\n| linkId | expected (v/status) | got (v/status) | value | status | quote |\n|---|---|---|---|---|---|\n`;
    for (const i of c.indicator) {
      md += `| ${i.linkId} | ${i.expected.value} / ${i.expected.status} | ${i.got ? `${i.got.value} / ${i.got.status}` : "—"} | ${i.valueMatch ? "✓" : "✗"} | ${i.statusMatch ? "✓" : "✗"} | ${i.quoteValid ? "✓" : "✗"} |\n`;
    }
    const fp = c.absent.filter((a) => a.falsePositive);
    md += `\nfalse positives (answered an \`expectedAbsent\` linkId): ${fp.length ? fp.map((a) => a.linkId).join(", ") : "none"}\n`;
    md += `\nexam/site selection — expected ${JSON.stringify(c.examSel?.expected)} · got ${JSON.stringify(c.examSel?.got)}\n`;
    md += `\nengine: determination ${c.engine?.determination} vs expected ${c.engine?.expected} — ${c.engine?.determination === c.engine?.expected ? "MATCH" : "DIVERGES"}\n`;
  }
  md += `\n`;
}

fs.mkdirSync(resultsDir, { recursive: true });
const outPath = path.join(resultsDir, `${date}-${provider}-${modelId}.md`.replace(/[^a-zA-Z0-9.\-]/g, "_"));
fs.writeFileSync(outPath, md);
console.log(`Wrote ${path.relative(path.join(here, "..", ".."), outPath)}`);
